// RecurringTask represents a recurring task with its specific fields
// Aligned with the database schema:
// CREATE TABLE "RecurringTasks" (
//
//	"recurring_task_id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
//	"user_id" integer NOT NULL,
//	"start_date" day_of_week_abbr NOT NULL,
//	"end_date" day_of_week_abbr,
//	"event_start_time" time NOT NULL,
//	"event_end_time" time NOT NULL,
//	"category_id" integer,
//	"title" varchar(255) NOT NULL,
//	"description" text,
//	"created_at" timestamp NOT NULL DEFAULT (now()),
//	"updated_at" timestamp DEFAULT (now())
//
// );
type RecurringTask struct {
	RecurringTaskID int        `json:"recurring_task_id"`
	UserID          int        `json:"user_id"`
	StartDate       DayOfWeek  `json:"start_date" binding:"required"`
	EndDate         *DayOfWeek `json:"end_date"`                            // Optional field
	EventStartTime  string     `json:"event_start_time" binding:"required"` // Time format: HH:MM:SS
	EventEndTime    string     `json:"event_end_time" binding:"required"`   // Time format: HH:MM:SS
	CategoryID      *int       `json:"category_id"`                         // Optional field
	Constraint      Constraint `json:"constraint" binding:"required"`
	Title           string     `json:"title" binding:"required"`
	Description     string     `json:"description"`
	CreatedAt       time.Time  `json:"created_at"`
	UpdatedAt       *time.Time `json:"updated_at"` // Optional field
}

func FetchRecurringTasksByIDs(userID int, taskIDs []int) ([]RecurringTask, error) {
	// Get database connection
	database := db.GetDB()
	if database == nil {
		return nil, fmt.Errorf("database connection error")
	}

	var recurringTasks []RecurringTask

	// Only proceed if we have task IDs to fetch
	if len(taskIDs) > 0 {
		// Create placeholders for the query
		placeholders := make([]string, len(taskIDs))
		args := make([]interface{}, len(taskIDs)+1)
		args[0] = userID // First argument is userID

		for i, id := range taskIDs {
			placeholders[i] = fmt.Sprintf("$%d", i+2) // +2 because $1 is userID
			args[i+1] = id
		}

		// Construct the query with dynamic placeholders
		query := fmt.Sprintf(`
			SELECT 
				"recurring_task_id", 
				"user_id", 
				"start_date", 
				"end_date", 
				"event_start_time", 
				"event_end_time", 
				"category_id", 
				"constraint",
				"title", 
				"description", 
				"created_at", 
				"updated_at"
			FROM "RecurringTasks"
			WHERE "user_id" = $1 AND "recurring_task_id" IN (%s);
		`, strings.Join(placeholders, ", "))

		// Execute the query
		rows, err := database.Query(query, args...)
		if err != nil {
			return nil, fmt.Errorf("failed to query recurring tasks: %w", err)
		}
		defer rows.Close()

		// Process the recurring tasks
		for rows.Next() {
			var task RecurringTask
			var startDateStr string
			var endDateStr sql.NullString
			var categoryID sql.NullInt32
			var description sql.NullString
			var constraintStr sql.NullString
			var updatedAt sql.NullTime

			// Match the number of fields in the SELECT query
			err := rows.Scan(
				&task.RecurringTaskID,
				&task.UserID,
				&startDateStr,
				&endDateStr,
				&task.EventStartTime,
				&task.EventEndTime,
				&categoryID,
				&constraintStr,
				&task.Title,
				&description,
				&task.CreatedAt,
				&updatedAt,
			)

			if err != nil {
				log.Printf("[ERROR] FetchRecurringTasksByIDs: Row scan failed: %v", err)
				continue
			}

			// Convert string to DayOfWeek type
			task.StartDate = DayOfWeek(startDateStr)

			// Handle nullable fields
			if endDateStr.Valid {
				endDateValue := DayOfWeek(endDateStr.String)
				task.EndDate = &endDateValue
			}

			if categoryID.Valid {
				catID := int(categoryID.Int32)
				task.CategoryID = &catID
			}

			if description.Valid {
				task.Description = description.String
			}

			if updatedAt.Valid {
				task.UpdatedAt = &updatedAt.Time
			}

			// Set constraint
			if constraintStr.Valid && constraintStr.String != "" {
				task.Constraint = Constraint(constraintStr.String)
			} else {
				task.Constraint = Hard // Default to Hard constraint
			}

			recurringTasks = append(recurringTasks, task)
		}

		// Check for errors in the query
		if err := rows.Err(); err != nil {
			log.Printf("[ERROR] FetchRecurringTasksByIDs: Error iterating rows: %v", err)
			return nil, fmt.Errorf("error processing recurring tasks: %w", err)
		}
	}

	return recurringTasks, nil
}

func ConvertRecurringTasksToGA(tasks []RecurringTask) []RecurringTaskGA {
	var result []RecurringTaskGA

	// Map day of week to integer (Mon=0, Tue=1, ..., Sun=6)
	dayToInt := map[DayOfWeek]int{
		Monday:    0,
		Tuesday:   1,
		Wednesday: 2,
		Thursday:  3,
		Friday:    4,
		Saturday:  5,
		Sunday:    6,
	}

	for _, task := range tasks {
		// Convert start and end days to integers
		startDate := dayToInt[task.StartDate]

		var endDate int
		if task.EndDate != nil {
			endDate = dayToInt[*task.EndDate]
		} else {
			// If end date not specified, use start date
			endDate = startDate
		}

		// Calculate slots based on event start/end times
		// Parse the time strings
		startTime, err := time.Parse("15:04:05", task.EventStartTime)
		if err != nil {
			log.Printf("[ERROR] convertRecurringTasksToGA: Invalid start time format: %v", err)
			continue

		}

		endTime, err := time.Parse("15:04:05", task.EventEndTime)
		if err != nil {
			log.Printf("[ERROR] convertRecurringTasksToGA: Invalid end time format: %v", err)
			endTime = startTime
		}

		// Calculate duration in minutes
		durationMinutes := int(endTime.Sub(startTime).Minutes())

		// Convert to 15-minute slots
		slots := durationMinutes / 15
		if durationMinutes%15 > 0 {
			slots++ // Round up to next 15-minute slot
		}

		// Default to at least 1 slot (15 minutes)
		if slots < 1 {
			slots = 1
		}

		gaTask := RecurringTaskGA{
			TaskId:    task.RecurringTaskID,
			StartDate: startDate,
			EndDate:   endDate,

			Slots:       slots,
			Constraint:  string(task.Constraint),
			Title:       task.Title,
			Description: task.Description,
		}

		result = append(result, gaTask)
	}

	return result
}

func CreateHardGene(schedule []RecurringTask) []int {
	var maxDay = GeneratePopulationSleep("21:00", "09:00")
	var dayPad = 84 - maxDay
	var hardGene = make([]int, 336) // Initialize the array with the correct length

	// Create empty schedule
	for x := 0; x < 7; x++ {
		for i := 0; i < dayPad; i++ {
			hardGene[x*48+i] = 0
		}
	}

	// Map day of week to integer (Mon=0, Tue=1, ..., Sun=6)
	dayToInt := map[DayOfWeek]int{
		Monday:    0,
		Tuesday:   1,
		Wednesday: 2,
		Thursday:  3,
		Friday:    4,
		Saturday:  5,
		Sunday:    6,
	}

	for x := range schedule {
		var startSlice, _ = timeUtils.TimeSliceFinder(schedule[x].EventStartTime)
		var endSlice, _ = timeUtils.TimeSliceFinder(schedule[x].EventEndTime)

		fmt.Println(startSlice, endSlice)

		// Calculate the start and end positions in the gene
		startSlice = startSlice - dayPad

		// Convert DayOfWeek to integer (0-6)
		dayOfWeekInt := dayToInt[schedule[x].StartDate]
		dayPadding := dayOfWeekInt * 48

		// Calculate duration
		duration, _ := timeUtils.TimeSliceDurationCalc(schedule[x].EventStartTime, schedule[x].EventEndTime)
		end := startSlice + duration + dayPadding

		// Add the task to the gene sequence
		for i := startSlice + dayPadding; i < end; i++ {
			if i >= 0 && i < len(hardGene) {
				hardGene[i] = schedule[x].RecurringTaskID // Use RecurringTaskID instead of TaskId
			}
		}
	}

	return hardGene
}

func GeneratePopulationSleep(startBed string, endBed string) int {
	const day = 96
	var padding, _ = timeUtils.TimeSleepDifference(startBed, endBed)
	return day - padding
}
