// RecurringTask represents a recurring task with its specific fields
// Aligned with the database schema:
// CREATE TABLE "RecurringTasks" (
//
//	"recurring_task_id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
//	"user_id" integer NOT NULL,
//	"start_date" day_of_week_abbr NOT NULL,
//	"end_date" day_of_week_abbr,
//	"event_start_time" time NOT NULL,
//	"event_end_time" time NOT NULL,
//	"category_id" integer,
//	"title" varchar(255) NOT NULL,
//	"description" text,
//	"created_at" timestamp NOT NULL DEFAULT (now()),
//	"updated_at" timestamp DEFAULT (now())
//
// );
type RecurringTask struct {
	RecurringTaskID int        `json:"recurring_task_id"`
	UserID          int        `json:"user_id"`
	StartDate       DayOfWeek  `json:"start_date" binding:"required"`
	EndDate         *DayOfWeek `json:"end_date"`                            // Optional field
	EventStartTime  string     `json:"event_start_time" binding:"required"` // Time format: HH:MM:SS
	EventEndTime    string     `json:"event_end_time" binding:"required"`   // Time format: HH:MM:SS
	CategoryID      *int       `json:"category_id"`                         // Optional field
	Constraint      Constraint `json:"constraint" binding:"required"`
	Title           string     `json:"title" binding:"required"`
	Description     string     `json:"description"`
	CreatedAt       time.Time  `json:"created_at"`
	UpdatedAt       *time.Time `json:"updated_at"` // Optional field
}

