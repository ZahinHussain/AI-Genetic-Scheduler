// GetRecurringTask retrieves a single recurring task by ID

func GetRecurringTasks(c *gin.Context) {
	// Enhanced debugging
	log.Printf("[DEBUG] GetRecurringTasks: Request received from %s for %s %s",
		c.ClientIP(), c.Request.Method, c.Request.URL.Path)

	// Check for userID in context
	userIDInter, exists := c.Get("userID")
	if !exists {
		log.Printf("[DEBUG] GetRecurringTasks: userID not found in context. Auth has failed.")
		c.JSON(http.StatusUnauthorized, gin.H{"error": "User not authenticated"})
		return
	}

	// Convert userID to an integer
	userID, ok := userIDInter.(int)
	if !ok {
		log.Printf("[DEBUG] GetRecurringTasks: userID is not an integer. Got: %T", userIDInter)
		c.JSON(http.StatusInternalServerError, gin.H{"error": "Invalid user ID"})
		return
	}

	log.Printf("[DEBUG] GetRecurringTasks: Authenticated userID: %v", userID)

	// Prepare the SQL query to match the actual table schema (11 columns, no constraint column)
	query := `
		SELECT 
			"recurring_task_id", 
			"user_id", 
			"start_date", 
			"end_date", 
			"event_start_time", 
			"event_end_time", 
			"category_id", 
			"title", 
			"description", 
			"created_at", 
			"updated_at"
		FROM "RecurringTasks"
		WHERE "user_id" = $1;
	`

	// Get database connection
	database := db.GetDB()
	if database == nil {
		log.Printf("[ERROR] GetRecurringTasks: Failed to get database connection")
		c.JSON(http.StatusInternalServerError, gin.H{"error": "Database connection error"})
		return
	}

	// Execute the query
	rows, err := database.Query(query, userID)
	if err != nil {
		log.Printf("[ERROR] GetRecurringTasks: Query failed: %v", err)
		c.JSON(http.StatusInternalServerError, gin.H{"error": "Query failed"})
		return
	}
	defer rows.Close()

	// Iterate over the result set
	var tasks []RecurringTask
	for rows.Next() {
		var t RecurringTask
		var categoryID sql.NullInt32
		var description sql.NullString
		var updatedAt sql.NullTime
		var endDate sql.NullString
		var startDateStr string

		if err := rows.Scan(
			&t.RecurringTaskID, // 1. recurring_task_id
			&t.UserID,          // 2. user_id
			&startDateStr,      // 3. start_date
			&endDate,           // 4. end_date
			&t.EventStartTime,  // 5. event_start_time
			&t.EventEndTime,    // 6. event_end_time
			&categoryID,        // 7. category_id
			&t.Title,           // 8. title
			&description,       // 9. description
			&t.CreatedAt,       // 10. created_at
			&updatedAt,         // 11. updated_at
		); err != nil {
			log.Printf("[ERROR] GetRecurringTasks: Row scan failed: %v", err)
			c.JSON(http.StatusInternalServerError, gin.H{"error": "Failed to retrieve tasks"})
			return
		}

		// Handle nullable fields
		if categoryID.Valid {
			catID := int(categoryID.Int32)
			t.CategoryID = &catID
		}
		if description.Valid {
			t.Description = description.String
		}
		if updatedAt.Valid {
			t.UpdatedAt = &updatedAt.Time
		}
		if endDate.Valid {
			endDateValue := DayOfWeek(endDate.String)
			t.EndDate = &endDateValue
		}

		// Convert string to DayOfWeek type
		t.StartDate = DayOfWeek(startDateStr)

		// Removed constraint handling as it's not in the table schema

		tasks = append(tasks, t)
	}

	// Check for errors after looping through rows
	if err = rows.Err(); err != nil {
		log.Printf("[ERROR] GetRecurringTasks: Rows error: %v", err)
		c.JSON(http.StatusInternalServerError, gin.H{"error": "Error reading tasks"})
		return
	}

	// Return tasks
	c.JSON(http.StatusOK, gin.H{
		"recurring_tasks": tasks,
	})
}

